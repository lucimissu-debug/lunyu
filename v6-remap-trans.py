# 取 char-level 特征集合
def feats(s):
    s = s or ""
    # 先算专有名词（权重高）
    score = 0
    hits = []
    # 强特征：专有名词，权重 5
    for w in PROPER:
        if w in s:
            score += 5
            hits.append(w)
    # 强特征：标志性完整句子，权重 12
    for w in UNIQUE_SENT:
        if len(w) >= 4 and w in s:
            score += 12
            hits.append(w)
    # 弱特征：按 2-gram 字（重合度），权重 0.3 每字
    # 只取高频字中的出现重合
    return score, set(hits)

# 给每条文言文和每条翻译都生成特征
lunyu_feats = []
for c in lunyu:
    sc, hs = feats(c.get("text",""))
    # 再加 title/人名词典中可能出现的
    sc2, hs2 = feats(c.get("title","") + " " + " ".join(c.get("persons_mentioned_auto", [])))
    lunyu_feats.append({"id": c["id"], "score": sc+sc2, "hits": hs|hs2, "text": c.get("text",""), "title": c.get("title","")})

