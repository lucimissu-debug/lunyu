for i in range(N):
    lc = lunyu_chars[i]
    lf = lunyu_feats[i]
    llen = lunyu_len[i]
    # 分数：专有名词交集 * 6 + 字集 Jaccard * 40 - 长度偏差惩罚
    # 长度比 译文/原文 合理区间 1.2 ~ 3.5 倍，偏离的罚分
    scores = []
    for j in range(M):
        # 专有名词/句子 hits 交集
        inter_hit = lf["hits"] & trans_feats[j]["hits"]
        hit_score = sum(6 if len(h)>=4 else 3 for h in inter_hit)
        # 字集 Jaccard
        tc = trans_chars[j]
        inter_ch = len(lc & tc)
        union_ch = len(lc | tc)
        jc = inter_ch / max(1, union_ch)
        char_score = jc * 40
        # 长度比惩罚（译文/原文）
        ratio = trans_len[j] / max(1, llen)
        # 理想比 2.1 左右；偏离越远罚越多
        len_pen = -abs(ratio - 2.1) * 2
        scores.append((hit_score + char_score + len_pen, j, hit_score, jc, ratio))
    scores.sort(key=lambda x: -x[0])
    top = scores[:TOPK]
    candidates.append(top)
